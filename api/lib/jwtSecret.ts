import { env } from "./env";

/**
 * Единый источник секрета для подписи/проверки JWT-токенов входа.
 *
 * Раньше три файла (api/trpc.ts, api/context.ts, api/boot.ts) независимо
 * друг от друга читали process.env.JWT_SECRET и у КАЖДОГО было своё
 * захардкоженное запасное значение на случай, если переменная не задана —
 * причём эти значения успели разъехаться между собой (опечатка в одном из
 * трёх). Такой fallback опасен сам по себе: он лежит открытым текстом в
 * публичном репозитории, и если JWT_SECRET забудут выставить на каком-то
 * окружении, авторизация тихо начнёт работать на общедоступном секрете
 * вместо явного падения сервера при старте.
 *
 * env.jwtSecret использует required() — без реального секрета в .env
 * сервер в production просто не запустится, тихого fallback больше нет.
 */
export const JWT_SECRET = new TextEncoder().encode(env.jwtSecret);
